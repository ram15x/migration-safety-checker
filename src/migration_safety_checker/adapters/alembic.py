"""Generate a migration-safety-checker configuration from an Alembic project's real revisions.

Given a checkout of the old release and one of the new release, the adapter asks
each checkout's own Alembic which revisions it has, takes the ones only the new
release has, and turns every one into a phase. The revision graph comes from
Alembic's ``ScriptDirectory``; the notes on risky operations come from reading the
``upgrade()`` function of each revision with ``ast``, so they are a hint and can
miss operations hidden inside helper functions.

Every command the generated configuration runs, migrations and application commands
alike, goes through a small wrapper, ``migration_safety_checker_alembic.py``, written next to it.
The wrapper builds the SQLAlchemy URL from ``DATABASE_URL`` and exports it as the
``sqlalchemy.url`` option and as the variables named by ``--url-env``; ``--url-part``
exports single parts (host, port, user, password, dbname) for applications that assemble
their own URL from separate settings.
"""

from __future__ import annotations

import json
import os
import shlex
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

from .django import AdapterError

MARKER = "MIGRATION-SAFETY-CHECKER-REVISIONS "
WRAPPER_NAME = "migration_safety_checker_alembic.py"

# Runs inside each release's own environment, so it needs only Alembic and the standard library.
WRAPPER = r'''"""Generated by migration-safety-checker. Runs Alembic against the prepared database."""
import ast
import json
import os
import subprocess
import sys
from urllib.parse import parse_qs, unquote, urlsplit

from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory

MARKER = "MIGRATION-SAFETY-CHECKER-REVISIONS "


def sqlalchemy_url():
    url = os.environ["DATABASE_URL"]
    driver = os.environ.get("MIGRATION_SAFETY_CHECKER_DRIVER", "")
    if driver and url.startswith("postgresql://"):
        url = "postgresql+" + driver + url[len("postgresql"):]
    return url


def url_parts():
    u = urlsplit(os.environ["DATABASE_URL"])
    host = parse_qs(u.query).get("host", [u.hostname or ""])[0]
    return {
        "host": host, "port": str(u.port or ""), "user": unquote(u.username or ""),
        "password": unquote(u.password or ""), "dbname": unquote(u.path.lstrip("/")),
    }


def apply_environment():
    """Export the prepared database's URL, and its parts, under the names the application reads."""
    url = sqlalchemy_url()
    for name in filter(None, os.environ.get("MIGRATION_SAFETY_CHECKER_URL_ENV", "").split(",")):
        os.environ[name] = url
    parts = url_parts()
    for item in filter(None, os.environ.get("MIGRATION_SAFETY_CHECKER_URL_PARTS", "").split(",")):
        name, part = item.split("=", 1)
        os.environ[name] = parts[part]
    return url


def make_config(ini):
    cfg = Config(ini)
    cfg.set_main_option("sqlalchemy.url", apply_environment().replace("%", "%%"))
    return cfg


def _const(node):
    return node.value if isinstance(node, ast.Constant) else None


def _kwargs(call):
    return {k.arg: k.value for k in call.keywords if k.arg}


def _describe(call):
    name = call.func.attr
    kw = _kwargs(call)
    if name == "add_column":
        for arg in call.args:
            if isinstance(arg, ast.Call) and getattr(arg.func, "attr", "") == "Column":
                ckw = _kwargs(arg)
                if _const(ckw.get("nullable")) is False and "server_default" not in ckw and "default" not in ckw:
                    return "add_column[not-null-no-default]"
        return name
    if name == "alter_column":
        if _const(kw.get("nullable")) is False:
            return "alter_column[not-null]"
        if "new_column_name" in kw:
            return "alter_column[rename]"
        if "type_" in kw:
            return "alter_column[type]"
    return name


def operations(path):
    try:
        tree = ast.parse(open(path, encoding="utf-8").read())
    except (OSError, SyntaxError):
        return []
    fn = next((n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "upgrade"), None)
    found = []
    for node in ast.walk(fn) if fn else []:
        if (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                and isinstance(node.func.value, ast.Name) and node.func.value.id.endswith("op")):
            found.append((node.lineno, node.col_offset, _describe(node)))
    return [desc for _, _, desc in sorted(found)]


def listing(ini):
    script = ScriptDirectory.from_config(make_config(ini))
    out = []
    for rev in reversed(list(script.walk_revisions("base", "heads"))):
        out.append({
            "rev": rev.revision,
            "down": [rev.down_revision] if isinstance(rev.down_revision, str) else list(rev.down_revision or []),
            "message": rev.doc or "",
            "ops": operations(rev.path),
        })
    print(MARKER + json.dumps(out))


def main(argv):
    if len(argv) < 4 or argv[1] != "--config":
        sys.exit("usage: migration_safety_checker_alembic.py --config alembic.ini (upgrade REV | list | exec COMMAND)")
    ini, action = argv[2], argv[3]
    if action == "exec" and len(argv) == 5:
        apply_environment()
        sys.exit(subprocess.call(argv[4], shell=True))
    if action == "list":
        listing(ini)
    elif action == "upgrade" and len(argv) == 5:
        command.upgrade(make_config(ini), argv[4])
    else:
        sys.exit("unknown action: " + " ".join(argv[3:]))


main(sys.argv)
'''

# Operations that remove or change something the old release may still use.
BREAKING_OPS = {
    "drop_column": "removes a column",
    "drop_table": "drops a table",
    "rename_table": "renames a table",
    "alter_column[rename]": "renames a column",
    "alter_column[not-null]": "makes a column NOT NULL; old writes and existing NULLs can break it",
    "alter_column[type]": "changes a column's type",
    "add_column[not-null-no-default]": "adds a NOT NULL column without a default; old inserts will fail",
    "create_unique_constraint": "adds a uniqueness rule that old writes may violate",
    "create_check_constraint": "adds a check constraint that old writes may violate",
    "create_foreign_key": "adds a foreign key that old writes may violate",
    "drop_constraint": "removes a constraint",
    "drop_index": "drops an index",
}
DATA_OPS = {"execute": "raw SQL or data migration", "bulk_insert": "data migration"}


@dataclass
class Revision:
    rev: str
    message: str
    ops: list[str]
    down: list[str] = field(default_factory=list)

    @property
    def label(self) -> str:
        slug = "_".join("".join(c if c.isalnum() else " " for c in self.message.lower()).split())
        return f"{self.rev}_{slug}"[:60] if slug else self.rev

    @property
    def notes(self) -> list[str]:
        notes = [f"{op}: {BREAKING_OPS[op]}" for op in self.ops if op in BREAKING_OPS]
        notes += [f"{op}: {DATA_OPS[op]}" for op in self.ops if op in DATA_OPS]
        return notes


@dataclass
class Release:
    """One checkout of the project and the interpreter that runs it."""

    directory: Path
    python: str
    test: str = ""


@dataclass
class Options:
    old: Release
    new: Release
    out: Path
    config: str = "alembic.ini"
    seed: str = ""
    write: str = ""
    read: str = ""
    env: dict[str, str] = field(default_factory=dict)
    url_env: list[str] = field(default_factory=lambda: ["DATABASE_URL"])
    url_parts: dict[str, str] = field(default_factory=dict)
    driver: str = ""
    migrate_first: bool = False
    name: str = ""
    timeout: int = 300


def _environment(opts: Options) -> dict[str, str]:
    env = dict(opts.env)
    env["MIGRATION_SAFETY_CHECKER_URL_ENV"] = ",".join(opts.url_env)
    if opts.url_parts:
        env["MIGRATION_SAFETY_CHECKER_URL_PARTS"] = ",".join(f"{k}={v}" for k, v in opts.url_parts.items())
    if opts.driver:
        env["MIGRATION_SAFETY_CHECKER_DRIVER"] = opts.driver
    return env


def discover(release: Release, opts: Options) -> list[Revision]:
    """List a release's revisions, oldest first, using its own Alembic."""
    wrapper = opts.out / WRAPPER_NAME
    run_env = {**os.environ, **_environment(opts)}
    run_env.setdefault("DATABASE_URL", "postgresql://discovery@localhost/none")  # listing never connects
    run_env["PYTHONPATH"] = os.pathsep.join(
        p for p in (str(release.directory), run_env.get("PYTHONPATH", "")) if p
    )
    try:
        proc = subprocess.run(
            [release.python, str(wrapper), "--config", opts.config, "list"],
            cwd=release.directory, env=run_env, capture_output=True, text=True, timeout=120,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise AdapterError(f"could not run {release.python} in {release.directory}: {exc}") from exc
    for line in proc.stdout.splitlines():
        if line.startswith(MARKER):
            return [Revision(**item) for item in json.loads(line[len(MARKER):])]
    tail = "\n".join((proc.stderr or proc.stdout).strip().splitlines()[-6:])
    raise AdapterError(f"could not load revisions from {release.directory} with '{opts.config}':\n{tail}")


def new_revisions(old: list[Revision], new: list[Revision]) -> list[Revision]:
    """Revisions only the new release has, in the new release's order."""
    known = {r.rev for r in old}
    return [r for r in new if r.rev not in known]


def _command(release: Release, opts: Options, args: str) -> str:
    wrapper = shlex.quote(str(opts.out / WRAPPER_NAME))
    env = {**_environment(opts), "PYTHONPATH": str(release.directory)}
    assignments = " ".join(f"{k}={shlex.quote(v)}" for k, v in env.items())
    return (
        f"cd {shlex.quote(str(release.directory))} && env {assignments} "
        f"{shlex.quote(release.python)} {wrapper} --config {shlex.quote(opts.config)} {args}"
    )


def _in_release(release: Release, opts: Options, command: str) -> str:
    """A user command run from the release's directory, with the database named the way the application expects.

    ``{python}`` in the command stands for the release's own interpreter.
    """
    command = command.replace("{python}", shlex.quote(release.python))
    return _command(release, opts, f"exec {shlex.quote(command)}")


def _q(text: str) -> str:
    return json.dumps(text)  # a JSON string is a valid double-quoted YAML scalar


def render(opts: Options, phases: list[Revision]) -> str:
    """Build the YAML text for the discovered phases."""
    lines = [
        f"# Generated by `migration-safety-checker init-alembic`. {len(phases)} phase(s) from the revisions",
        "# present in the new release and absent from the old one. Review before relying on it.",
        f"name: {_q(opts.name or 'alembic rolling deploy')}",
        f"timeout: {opts.timeout}",
        "baseline:",
        "  run:",
        f"    - {_q(_command(opts.old, opts, 'upgrade heads'))}",
    ]
    if opts.seed:
        lines.append(f"    - {_q(_in_release(opts.old, opts, opts.seed))}")
    else:
        lines.insert(-1, "  # No --seed given: data migrations below run against empty tables.")
    lines.append("phases:")
    if opts.migrate_first:
        lines.insert(-1, "# --migrate-first: every revision is applied before the new release starts, so the new release is only")
        lines.insert(-1, "# required to work on the state after the last revision; the old release must work on all of them.")
    for i, r in enumerate(phases):
        for note in r.notes:
            lines.append(f"  # {r.label}  {note}")
        if "execute" in r.ops or "bulk_insert" in r.ops:
            lines.append(f"  # {r.label}  add partial_run to test a half-finished backfill")
        lines += [
            f"  - name: {_q(r.label)}",
            "    run:",
            f"      - {_q(_command(opts.new, opts, f'upgrade {r.rev}'))}",
        ]
        if opts.migrate_first and i < len(phases) - 1:
            lines.append("    new_may_run: false")
    lines.append("apps:")
    for side, rel in (("old", opts.old), ("new", opts.new)):
        lines.append(f"  {side}:")
        lines.append(f"    test: {_q(_in_release(rel, opts, rel.test))}")
        if opts.write:
            lines.append(f"    write: {_q(_in_release(rel, opts, opts.write))}")
        if opts.read:
            lines.append(f"    read: {_q(_in_release(rel, opts, opts.read))}")
    return "\n".join(lines) + "\n"


def generate(opts: Options) -> tuple[Path, list[Revision]]:
    """Write ``migration-safety-checker.yml`` and the Alembic wrapper into ``opts.out``; return the YAML path."""
    for rel, label in ((opts.old, "old"), (opts.new, "new")):
        if not (rel.directory / opts.config).is_file():
            raise AdapterError(f"{label} checkout has no {opts.config}: {rel.directory}")
        if not rel.test.strip():
            raise AdapterError(f"no test command for the {label} release (use --test)")
    opts.out.mkdir(parents=True, exist_ok=True)
    (opts.out / WRAPPER_NAME).write_text(WRAPPER)
    old = discover(opts.old, opts)
    new = discover(opts.new, opts)
    phases = new_revisions(old, new)
    if not phases:
        raise AdapterError("the new release has no revisions the old release lacks; nothing to check")
    path = opts.out / "migration-safety-checker.yml"
    path.write_text(render(opts, phases))
    return path, phases
