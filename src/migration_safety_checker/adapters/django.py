"""Generate a Migration Safety Checker configuration from a Django project's real migrations.

Given a checkout of the old release and one of the new release, the adapter asks
each checkout's own Django which migrations it has, takes the ones only the new
release has, and turns every one into a phase. Nothing is guessed from file names:
the migration graph comes from Django's loader.
"""

from __future__ import annotations

import json
import os
import shlex
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

DISCOVER = r"""
import json, django
django.setup()
from django.db.migrations.loader import MigrationLoader
loader = MigrationLoader(None, ignore_no_migrations=True)
graph, seen, out = loader.graph, set(), []
for leaf in sorted(graph.leaf_nodes()):
    for node in graph.forwards_plan(leaf):
        if node in seen:
            continue
        seen.add(node)
        mig = loader.disk_migrations.get(node)
        ops = [type(op).__name__ for op in getattr(mig, "operations", [])]
        out.append({"app": node[0], "name": node[1], "ops": ops})
print("MIGRATION-SAFETY-CHECKER-MIGRATIONS " + json.dumps(out))
"""

# Operations that remove or change something the old release may still use.
BREAKING_OPS = {
    "RemoveField": "removes a column",
    "DeleteModel": "drops a table",
    "RenameField": "renames a column",
    "RenameModel": "renames a table",
    "AlterModelTable": "renames a table",
    "AlterField": "changes a column; check nullability, type and defaults",
    "AlterUniqueTogether": "changes a uniqueness rule",
    "AlterIndexTogether": "changes an index",
    "AddConstraint": "adds a constraint that old writes may violate",
    "RemoveConstraint": "removes a constraint",
}
DATA_OPS = {"RunPython": "data migration", "RunSQL": "raw SQL"}


class AdapterError(Exception):
    """The project could not be inspected."""


@dataclass
class Migration:
    app: str
    name: str
    ops: list[str]

    @property
    def key(self) -> tuple[str, str]:
        return (self.app, self.name)

    @property
    def notes(self) -> list[str]:
        notes = [f"{op}: {BREAKING_OPS[op]}" for op in self.ops if op in BREAKING_OPS]
        notes += [f"{op}: {DATA_OPS[op]}" for op in self.ops if op in DATA_OPS]
        return notes


@dataclass
class Release:
    """One checkout of the project and the interpreter that runs it."""

    directory: Path
    python: str


@dataclass
class Options:
    old: Release
    new: Release
    settings: str
    out: Path
    manage: str = "manage.py"
    test_labels: str = ""
    seed: Path | None = None
    write: Path | None = None
    read: Path | None = None
    env: dict[str, str] = field(default_factory=dict)
    name: str = ""
    timeout: int = 300


def discover(release: Release, settings: str, env: dict[str, str]) -> list[Migration]:
    """List a release's migrations in dependency order, using its own Django."""
    run_env = {**os.environ, **env, "DJANGO_SETTINGS_MODULE": settings}
    run_env["PYTHONPATH"] = os.pathsep.join(
        p for p in (str(release.directory), run_env.get("PYTHONPATH", "")) if p
    )
    try:
        proc = subprocess.run(
            [release.python, "-c", DISCOVER],
            cwd=release.directory, env=run_env, capture_output=True, text=True, timeout=120,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise AdapterError(f"could not run {release.python} in {release.directory}: {exc}") from exc
    for line in proc.stdout.splitlines():
        if line.startswith("MIGRATION-SAFETY-CHECKER-MIGRATIONS "):
            return [Migration(**item) for item in json.loads(line[len("MIGRATION-SAFETY-CHECKER-MIGRATIONS "):])]
    tail = "\n".join((proc.stderr or proc.stdout).strip().splitlines()[-6:])
    raise AdapterError(
        f"could not load migrations from {release.directory} with settings '{settings}':\n{tail}"
    )


def new_migrations(old: list[Migration], new: list[Migration]) -> list[Migration]:
    """Migrations only the new release has, in the new release's order."""
    known = {m.key for m in old}
    return [m for m in new if m.key not in known]


def _command(release: Release, opts: Options, args: str) -> str:
    package_root = Path(__file__).resolve().parents[2]  # directory holding `migration_safety_checker`
    pythonpath = os.pathsep.join([str(opts.out), str(release.directory), str(package_root)])
    env = {"DJANGO_SETTINGS_MODULE": "migration_safety_checker_settings", "PYTHONPATH": pythonpath, **opts.env}
    assignments = " ".join(f"{k}={shlex.quote(v)}" for k, v in env.items())
    return (
        f"cd {shlex.quote(str(release.directory))} && env {assignments} "
        f"{shlex.quote(release.python)} {args}"
    )


def settings_overlay(settings: str) -> str:
    return (
        '"""Generated by migration-safety-checker. Points a Django project at the prepared database."""\n'
        "import os\n\n"
        f"from {settings} import *  # noqa: F401,F403\n"
        "from migration_safety_checker.django_support import database_from_env\n\n"
        'os.environ["MIGRATION_SAFETY_CHECKER_BASE_RUNNER"] = globals().get("TEST_RUNNER") or "django.test.runner.DiscoverRunner"\n'
        'DATABASES = {"default": database_from_env()}\n'
        'TEST_RUNNER = "migration_safety_checker.django_runner.Runner"\n'
        'ALLOWED_HOSTS = ["*"]\n'
    )


def _q(text: str) -> str:
    return json.dumps(text)  # a JSON string is a valid double-quoted YAML scalar


def render(opts: Options, phases: list[Migration]) -> str:
    """Build the YAML text for the discovered phases."""
    migrate = f"{opts.manage} migrate -v0"
    suite = f"{opts.manage} test {opts.test_labels} --noinput".replace("  ", " ")
    lines = [
        f"# Generated by `migration-safety-checker init-django`. {len(phases)} phase(s) from the migrations",
        "# present in the new release and absent from the old one. Review before relying on it.",
        f"name: {_q(opts.name or 'django rolling deploy')}",
        f"timeout: {opts.timeout}",
        "baseline:",
        "  run:",
        f"    - {_q(_command(opts.old, opts, migrate))}",
    ]
    if opts.seed:
        lines.append(f"    - {_q(_command(opts.old, opts, str(opts.seed.resolve())))}")
    else:
        lines.insert(-1, "  # No --seed given: data migrations below run against empty tables.")
    lines.append("phases:")
    for m in phases:
        for note in m.notes:
            lines.append(f"  # {m.app}.{m.name}  {note}")
        if "RunPython" in m.ops or "RunSQL" in m.ops:
            lines.append(f"  # {m.app}.{m.name}  add partial_sql to test a half-finished backfill")
        lines += [
            f"  - name: {_q(m.app + '.' + m.name)}",
            "    run:",
            f"      - {_q(_command(opts.new, opts, f'{opts.manage} migrate {m.app} {m.name} -v0'))}",
        ]
    lines.append("apps:")
    for side, rel in (("old", opts.old), ("new", opts.new)):
        lines.append(f"  {side}:")
        lines.append(f"    test: {_q(_command(rel, opts, suite))}")
        if opts.write:
            lines.append(f"    write: {_q(_command(rel, opts, str(opts.write.resolve())))}")
        if opts.read:
            lines.append(f"    read: {_q(_command(rel, opts, str(opts.read.resolve())))}")
    return "\n".join(lines) + "\n"


def generate(opts: Options) -> tuple[Path, list[Migration]]:
    """Write ``migration-safety-checker.yml`` and ``migration_safety_checker_settings.py`` into ``opts.out``; return the YAML path."""
    for rel, label in ((opts.old, "old"), (opts.new, "new")):
        if not (rel.directory / opts.manage).is_file():
            raise AdapterError(f"{label} checkout has no {opts.manage}: {rel.directory}")
    opts.out.mkdir(parents=True, exist_ok=True)
    (opts.out / "migration_safety_checker_settings.py").write_text(settings_overlay(opts.settings))
    # discovery runs the project's own settings, not the overlay (no database needed)
    old = discover(opts.old, opts.settings, opts.env)
    new = discover(opts.new, opts.settings, opts.env)
    phases = new_migrations(old, new)
    if not phases:
        raise AdapterError("the new release has no migrations that the old release lacks")
    path = opts.out / "migration-safety-checker.yml"
    path.write_text(render(opts, phases))
    return path, phases
